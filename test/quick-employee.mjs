import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
mkdirSync("test/_shots/simple", { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 320, height: 900 } });
const page = await ctx.newPage();
await page.goto("http://localhost:5173/login", { waitUntil: "domcontentloaded" });
await page.fill('input[type="email"]', "employee.it@scm.com");
await page.fill('input[type="password"]', "password");
await page.click('button[type="submit"]');
await page.waitForURL(/\/app\b/, { timeout: 30000 });
await page.waitForLoadState("networkidle", { timeout: 3000 }).catch(() => {});
await page.waitForTimeout(1200);
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight / 2));
await page.waitForTimeout(400);
await page.screenshot({ path: "test/_shots/simple/employee-320-scrolled.png", fullPage: false });
const x = await page.evaluate(() => ({ s: document.documentElement.scrollWidth, v: document.documentElement.clientWidth }));
console.log("320px →", x.v, "/", x.s, x.s > x.v ? "OVERFLOW" : "clean");
await browser.close();
